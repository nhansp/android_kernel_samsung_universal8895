#ifndef _DT_BINDINGS_IOMMU_EXYNOS_SYSMMU_H
#define _DT_BINDINGS_IOMMU_EXYNOS_SYSMMU_H

/* Way type, bits [13:12] of the configuration cell */
#define SYSMMU_WAY_TYPE_MASK		(0x3 << 12)
#define SYSMMU_WAY_PRIVATE_ID		(0x0 << 12)
#define SYSMMU_WAY_PRIVATE_ADDR		(0x1 << 12)
#define SYSMMU_WAY_PUBLIC		(0x2 << 12)

#define _SYSMMU_TARGET_READ		(0x1 << 8)
#define _SYSMMU_TARGET_WRITE		(0x2 << 8)
#define _SYSMMU_TARGET_READWRITE	(0x3 << 8)

#define _SYSMMU_DIR_DESCENDING		(0x0 << 2)
#define _SYSMMU_DIR_ASCENDING		(0x1 << 2)
#define _SYSMMU_DIR_PREDICTION		(0x2 << 2)

#define _SYSMMU_PREFETCH_ENABLE		(0x1 << 1)
#define _SYSMMU_PREFETCH_DISABLE	(0x0 << 1)

#define SYSMMU_ID(id)			(0xFFFF << 16 | (id))
#define SYSMMU_ID_MASK(id, mask)	((mask) << 16 | (id))
#define SYSMMU_NOID			0

#define SYSMMU_BL1			(0x0 << 5)
#define SYSMMU_BL2			(0x1 << 5)
#define SYSMMU_BL4			(0x2 << 5)
#define SYSMMU_BL8			(0x3 << 5)
#define SYSMMU_BL16			(0x4 << 5)
#define SYSMMU_BL32			(0x5 << 5)

#define SYSMMU_PUBLIC_NO_PREFETCH	(SYSMMU_WAY_PUBLIC | _SYSMMU_PREFETCH_DISABLE)
#define SYSMMU_PUBLIC_PREFETCH_ASCENDING	\
	(SYSMMU_WAY_PUBLIC | _SYSMMU_PREFETCH_ENABLE | _SYSMMU_DIR_ASCENDING)

#define SYSMMU_PRIV_ID_NO_PREFETCH_READ		\
	(SYSMMU_WAY_PRIVATE_ID | _SYSMMU_TARGET_READ | _SYSMMU_PREFETCH_DISABLE)
#define SYSMMU_PRIV_ID_NO_PREFETCH_WRITE	\
	(SYSMMU_WAY_PRIVATE_ID | _SYSMMU_TARGET_WRITE | _SYSMMU_PREFETCH_DISABLE)
#define SYSMMU_PRIV_ID_PREFETCH_ASCENDING_READ	\
	(SYSMMU_WAY_PRIVATE_ID | _SYSMMU_TARGET_READ | _SYSMMU_DIR_ASCENDING | \
	 _SYSMMU_PREFETCH_ENABLE)
#define SYSMMU_PRIV_ID_PREFETCH_ASCENDING_WRITE	\
	(SYSMMU_WAY_PRIVATE_ID | _SYSMMU_TARGET_WRITE | _SYSMMU_DIR_ASCENDING | \
	 _SYSMMU_PREFETCH_ENABLE)
#define SYSMMU_PRIV_ID_PREFETCH_PREDICTION_READ	\
	(SYSMMU_WAY_PRIVATE_ID | _SYSMMU_TARGET_READ | _SYSMMU_DIR_PREDICTION | \
	 _SYSMMU_PREFETCH_ENABLE)
#define SYSMMU_PRIV_ID_PREFETCH_PREDICTION_WRITE	\
	(SYSMMU_WAY_PRIVATE_ID | _SYSMMU_TARGET_WRITE | _SYSMMU_DIR_PREDICTION | \
	 _SYSMMU_PREFETCH_ENABLE)

#define SYSMMU_PRIV_ADDR_NO_PREFETCH_READ	\
	(SYSMMU_WAY_PRIVATE_ADDR | _SYSMMU_TARGET_READ | _SYSMMU_PREFETCH_DISABLE)
#define SYSMMU_PRIV_ADDR_NO_PREFETCH_WRITE	\
	(SYSMMU_WAY_PRIVATE_ADDR | _SYSMMU_TARGET_WRITE | _SYSMMU_PREFETCH_DISABLE)
#define SYSMMU_PRIV_ADDR_NO_PREFETCH_READWRITE	\
	(SYSMMU_WAY_PRIVATE_ADDR | _SYSMMU_TARGET_READWRITE | _SYSMMU_PREFETCH_DISABLE)
#define SYSMMU_PRIV_ADDR_PREFETCH_ASCENDING_READ	\
	(SYSMMU_WAY_PRIVATE_ADDR | _SYSMMU_TARGET_READ | _SYSMMU_DIR_ASCENDING | \
	 _SYSMMU_PREFETCH_ENABLE)

#endif /* _DT_BINDINGS_IOMMU_EXYNOS_SYSMMU_H */
