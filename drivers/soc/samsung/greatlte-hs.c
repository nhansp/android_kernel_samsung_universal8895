	hs_begin("pmu");
	for (i = 0; i < ARRAY_SIZE(hs_pmu_regs); i++)
		hs_add_word(hs_pmu_regs[i].key, HS_PMU + hs_pmu_regs[i].pa);
	hs_add(" cpust=");
	for_each_possible_cpu(cpu) {
		u64 m = cpu_logical_map(cpu);	/* A:arch/arm64/include/asm/smp.h:38 */
		unsigned int a0 = MPIDR_AFFINITY_LEVEL(m, 0), a1 = MPIDR_AFFINITY_LEVEL(m, 1);

		/* only the 8 stock slots (aff1 0..1, aff0 0..3): A:arch/arm64/include/asm/cputype.h:21-22 */
		if (MPIDR_AFFINITY_LEVEL(m, 2) || MPIDR_AFFINITY_LEVEL(m, 3) || a1 > 1 || a0 > 3)
			r = -ERANGE;
		else
			r = hs_rd(HS_PMU + HS_PMU_CPU_ST + ((a1 << 2) | a0) * HS_PMU_CPU_STEP, &v[0]);
		if (r)
			hs_add("%s!%d", k++ ? "/" : "", r);
		else
			hs_add("%s%x", k++ ? "/" : "", v[0]);
	}
	hs_end();

