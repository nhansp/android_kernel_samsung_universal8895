/*
 * greatlte hand-off snapshot "hs": the state S-Boot left in the PMU, the CMUs,
 * the APM SRAM, the DPU, UFS and USB, read once. DEBUG ONLY, read-only.
 * Spec: REWRITE_PLAN.md 4.4 (commit K9, 3.2); printer hook T_tooling.md 5.7.6.
 *
 * A delayed work fires once, hs.at_ms (default 130000) ms after boot. For each
 * block, in the order pmu, asv, cmu, cpll, apm, dpu, ufs, usb, it prints the
 * marker "hb: v1 hsm blk=<name>" at KERN_ERR and waits until the consoles have
 * written it, so that a bus hang is named by the last marker in the pstore
 * zone. Then it evaluates the block's guards and reads the listed registers
 * with 32-bit readl() from ioremap()s of exactly the 4 KiB pages that hold
 * them. Nothing is written anywhere. A guard that cannot be evaluated counts
 * as "off": the read it protects is skipped. hs.skip=<name>[,<name>...] skips
 * whole blocks (no marker, no access).
 * Only after the last block are the cached records handed to the heartbeat, as
 * slow printers "hs", "hs1", ... (one GREATLTE_HB_TEXT buffer each, records
 * never split), layer 0, every_ms 600000, so T's cadence prints them once per
 * run. Registering from a built-in delayed work (bool Kconfig, never
 * unregistered) instead of an initcall: plan 4.4.
 *
 * Records ("hb: v1 hs[<k>] seq=<n> age=<ms> <record>"; each starts blk=<b>).
 * Register values are hex without 0x; kHz, n= and counts are decimal.
 * "skip" = a guard found the block off or gated (an answer, not an error);
 * "!<errno>" = not read: -12 page not mapped, -34 outside the APM SRAM or the
 * PMU CPU slots, -22 misaligned SRAM pointer, -33 PLL P = 0.
 *   blk=pmu rst= inf2= inf3= psh= rsc= wd= sw= pmu704= pmu710= pmu71c= pmu724=
 *           pmu620= ck0= ck1= apmcfg= cpust=<cpu0>/.../<cpu7>
 *   blk=pmu rec=pd <label>=<cfg>/<status>/<option> (16 domains)
 *   blk=asv w=<w0>/<w1>/<w2>/<w3> ver=<w3 & 0x7f>
 *   blk=cmu cmu=<top|peris|peric0|peric1|fsys0|fsys1|apm> [tf=<digit of the
 *           TOP gate feeding this CMU; not for top>] n=<gates>
 *           d=<one digit per gate, hs_gates_* order> m0=<offsets whose digit
 *           is 1 or 5, at most 16, then ,+<more>; - if none>
 *           (d=skip m0=skip: the TOP feed is gated, the CMU is not read)
 *   blk=cmu rec=rate sh0= sh1= sh2= sh3= sh4= ufsm= ufsd= usbm= usbd= dpum=
 *           dpud= f0ufs= f0usb= f0qch= (the f0 words skip with a gated FSYS0 feed)
 *   blk=cpll cl0=<con0>/<kHz> cl1=<con0>/<kHz>
 *   blk=apm rec=fw <struct acpm_framework words 0-21 by name>
 *   blk=apm rec=ch n= at= c<i>=id/field/owner/type/rxrear/rxfront/txrear/
 *           txfront/qlen/qelem/appoll (4 channels per record)
 *   blk=apm rec=plg n= at= p<j>=id/base/attached/size/stay/fwname (6 per record)
 *   blk=dpu pd0= pd1= tg= n= d=<63 digits> m0= drcg0= g1s= drcg1=
 *   blk=dpu rec=ip gc= tr= d0= d1= d2= dsc= g0e= g0c= g0y= m1c= m1f= m1p= m1v=
 *           m1a= m1b= ls3= dps= cfg= pll= lp= dl= te=
 *           (m1a only if m1v's major version is >= 7, m1b only if m1a bit 11)
 *   blk=ufs tf=<FSYS0 feed digit> ga= gu= qch= cap= ver=
 *   blk=usb pmu704= tf=<FSYS0 feed digit> g= dp=<7 digits, x = unreadable> qch=
 *           v0= v1= rclk= snps=
 *   blk=end n=<records incl. this one> drop=<records that did not fit> ms=<run time>
 * Gate digit of a CLK_CON_GAT word = (bit28 << 2) | (bit21 << 1) | bit20
 * (ENABLE_AUTOMATIC_CLKGATING, CG_VAL, MANUAL: S:drivers/soc/samsung/cal-if/
 * exynos8895/cmucal-sfr.c:5322-5324; S:drivers/soc/samsung/cal-if/ra.c:381-384):
 * 0/2 no HWACG, clock on; 4/6 HWACG; 3/7 manual on; 1/5 manual gated.
 */
