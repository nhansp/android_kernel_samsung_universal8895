static void ex_phy_write_tables(struct exynos8895_pcie *pcie)
{
	u32 i;

	for (i = 0; i < ARRAY_SIZE(ex_cmn); i++)
		writel(ex_cmn[i], pcie->phy + EX_PHY_REG(EX_PHY_CMN_BASE + i));
	for (i = 0; i < ARRAY_SIZE(ex_trsv); i++)
		writel(ex_trsv[i], pcie->phy + EX_PHY_REG(EX_PHY_TRSV_BASE + i));
}

void ex_phy_config(struct exynos8895_pcie *pcie)
{
	u32 v;

	/* Undocumented sysreg and PCS bits: values of the vendor sequence */
	regmap_update_bits(pcie->sysreg, pcie->sysreg_off + EX_SYSREG_PHY0, BIT(1), 0);
	regmap_read(pcie->sysreg, pcie->sysreg_off + EX_SYSREG_WIFI0_PCIE_PHY_CONTROL, &v);
	v = (((v & ~(0xf << 4)) & ~(0xf << 2)) | (0x3 << 2)) & ~(0x1 << 1);
	regmap_write(pcie->sysreg, pcie->sysreg_off + EX_SYSREG_WIFI0_PCIE_PHY_CONTROL, v);

	ex_elbi_wr(pcie, EX_ELBI_MAC_RST, 0);
	udelay(10);
	ex_elbi_wr(pcie, EX_ELBI_PHY_CMN_RST, 0);
	udelay(10);
	ex_elbi_wr(pcie, EX_ELBI_PHY_PCS_GRST, 1);
	udelay(10);
	ex_elbi_wr(pcie, EX_ELBI_PHY_PCS_GRST, 0);
	udelay(10);
	ex_elbi_wr(pcie, EX_ELBI_PHY_PCS_GRST, 1);
	udelay(10);

	ex_phy_write_tables(pcie);

	writel(0x14, pcie->phy + EX_PHY_REG(EX_PHY_TX_AMPLITUDE));
	writel(0x70, pcie->pcs + EX_PCS_TX_LATENCY);
	writel(0x87, pcie->pcs + EX_PCS_REFCLK_OUT0);
	writel(0x50, pcie->pcs + EX_PCS_REFCLK_OUT1);
	v = readl(pcie->pcs + EX_PCS_L1SS_TIMEOUT);
	v &= ~BIT(1);
	v |= BIT(4);
	writel(v, pcie->pcs + EX_PCS_L1SS_TIMEOUT);

	ex_elbi_wr(pcie, EX_ELBI_MAC_RST, 1);
	udelay(10);
	ex_elbi_wr(pcie, EX_ELBI_PHY_CMN_RST, 1);
	udelay(10);

	/* The vendor sequence writes the tables again, which also resets the TX amplitude */
	ex_phy_write_tables(pcie);
}

void ex_phy_all_pwrdn(struct exynos8895_pcie *pcie)
{
	writel(0xFE, pcie->phy + EX_PHY_REG(EX_PHY_TRSV0_PWRDN));
	writel(0xC1, pcie->phy + EX_PHY_REG(EX_PHY_CMN_PWRDN));
}

/* As in the vendor driver, this releases the channel 1 transceiver, not channel 0 */
void ex_phy_all_pwrdn_clear(struct exynos8895_pcie *pcie)
{
	writel(0xC0, pcie->phy + EX_PHY_REG(EX_PHY_CMN_PWRDN));
	writel(0x7E, pcie->phy + EX_PHY_REG(EX_PHY_TRSV1_PWRDN));
}
