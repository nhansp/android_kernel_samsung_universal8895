void ex_phy_config(struct exynos8895_pcie *ep)			/* cal:145-229 */
{
	u32 i, v;

	BUILD_BUG_ON(ARRAY_SIZE(ex_cmn) != 48 || ARRAY_SIZE(ex_trsv) != 156);

	regmap_update_bits(ep->sysreg, ep->sysreg_off + 0x0, BIT(1), 0);			/* :168 */
	regmap_read(ep->sysreg, ep->sysreg_off + 0xc, &v);					/* :169 */
	v = (((v & ~(0xf << 4)) & ~(0xf << 2)) | (0x3 << 2)) & ~(0x1 << 1);
	regmap_write(ep->sysreg, ep->sysreg_off + 0xc, v);
	ex_elbi_wr(ep, 0x290, 0); udelay(10); ex_elbi_wr(ep, 0x28c, 0); udelay(10);		/* :171-176 */
	ex_elbi_wr(ep, 0x288, 1); udelay(10); ex_elbi_wr(ep, 0x288, 0); udelay(10);
	ex_elbi_wr(ep, 0x288, 1); udelay(10);							/* :177-183 */
	for (i = 0; i < 48; i++)
		writel(ex_cmn[i], ep->phy + i * 4);						/* :186-187 */
	for (i = 0; i < 156; i++)
		writel(ex_trsv[i], ep->phy + (0x30 + i) * 4);					/* :190-191 */
	/* :193-196 OTP tuning: CONFIG_EXYNOS_OTP absent from IKC (python grep) -> not compiled in stock, not ported */
	writel(0x14, ep->phy + 0x5c * 4);							/* :199 tx amplitude */
	writel(0x70, ep->pcs + 0xf8);								/* :202 tx latency */
	writel(0x87, ep->pcs + 0x100); writel(0x50, ep->pcs + 0x104);				/* :204-205 refclk out */
	v = readl(ep->pcs + 0xc); v &= ~BIT(1); v |= BIT(4); writel(v, ep->pcs + 0xc);		/* :208-211 L1SS timeout */
	ex_elbi_wr(ep, 0x290, 1); udelay(10); ex_elbi_wr(ep, 0x28c, 1); udelay(10);		/* :213-219 */
	for (i = 0; i < 48; i++)
		writel(ex_cmn[i], ep->phy + i * 4);						/* :221-224 "Re-write at Kangchen only" */
	for (i = 0; i < 156; i++)
		writel(ex_trsv[i], ep->phy + (0x30 + i) * 4);					/* :226-227 (overwrites PHY 0x5c*4 with ex_trsv[44] = 0xAC; stock behaviour) */
}

void ex_phy_all_pwrdn(struct exynos8895_pcie *ep)		/* cal:55-80, ch 0 */
{
	writel(0xFE, ep->phy + 0x57 * 4);
	writel(0xC1, ep->phy + 0x20 * 4);
}

void ex_phy_all_pwrdn_clear(struct exynos8895_pcie *ep)		/* cal:83-103, ch 0 */
{
	writel(0xC0, ep->phy + 0x20 * 4);
	writel(0x7E, ep->phy + 0xA7 * 4);
}
